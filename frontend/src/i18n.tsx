const dictionaries: Record<Lang, Record<TranslationKey, string>> = { en, de, tr }

interface I18nContextValue {
  lang: Lang
  setLang: (lang: Lang) => void
  t: (key: TranslationKey, params?: Record<string, string | number>) => string
}

const I18nContext = createContext<I18nContextValue>({
  lang: 'en',
  setLang: () => {},
  t: (key) => en[key] ?? key,
})

function loadLang(): Lang {
  const stored = localStorage.getItem('pdm-lang')
  return stored === 'tr' || stored === 'de' ? stored : 'en'
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(loadLang)

  useEffect(() => {
    localStorage.setItem('pdm-lang', lang)
    document.documentElement.lang = lang
  }, [lang])

  const setLang = useCallback((next: Lang) => setLangState(next), [])

  const t = useCallback(
    (key: TranslationKey, params?: Record<string, string | number>) => {
      let text: string = dictionaries[lang][key] ?? en[key] ?? key
      if (params) {
        for (const [name, value] of Object.entries(params)) {
          text = text.replace(`{${name}}`, String(value))
        }
      }
      return text
    },
    [lang],
  )

  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext)
}
